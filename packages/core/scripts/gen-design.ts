import { readFileSync, writeFileSync } from "node:fs";
import { DESIGN_FILES, extractDesign } from "./design-extract.ts";

const [html, readme] = DESIGN_FILES.map((p) => readFileSync(p, "utf8"));
const body = JSON.stringify(extractDesign(html, readme), null, 2);
writeFileSync("src/design.generated.ts", `// Generated by scripts/gen-design.ts from design-docnew. Do not edit.\nexport const design = ${body} as const;\n`);
