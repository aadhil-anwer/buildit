import { readFileSync, writeFileSync } from "node:fs";
import { buildTokens, DESIGN_FILES } from "../src/theme/build-tokens.ts";

const [css, readme] = DESIGN_FILES.map((p) => readFileSync(p, "utf8"));
const body = JSON.stringify(buildTokens(css, readme), null, 2);
writeFileSync("src/theme/tokens.generated.ts", `// Generated by scripts/gen-tokens.ts from design-docnew. Do not edit.\nexport const tokens = ${body} as const;\n`);
